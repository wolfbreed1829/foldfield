// Run with Playwright browser_run_code_unsafe, passing this filename.
async (page) => {
  const out='C:/experimentalbuilds/experiment-zero/build';
  const origin='http://127.0.0.1:4179/';
  const checks=[],errors=[];
  const check=(name,value)=>{if(!value)throw Error(name);checks.push(name);};
  const scene=()=>page.evaluate(async()=>JSON.parse((await import('./core/web_core.mjs')).describe(localStorage.getItem('foldfield.browser.v1'))));
  const ready=()=>page.waitForSelector('html[data-ready="true"]');
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(origin);await ready();
  await page.evaluate(()=>localStorage.removeItem('foldfield.browser.v1'));await page.reload();await ready();
  check('Empty page loads verified kernels',await page.locator('#empty').isVisible()&&await page.locator('#count').innerText()==='00');
  const canvas=page.locator('#fabric');let box=await canvas.boundingBox();
  await canvas.click({position:{x:box.width*.3,y:box.height*.3}});
  check('Canvas click adds positive source',(await scene()).sources[0][2]===1);
  await canvas.click({position:{x:box.width*.7,y:box.height*.65},button:'right'});
  check('Right click adds negative source',(await scene()).sources[1][2]===-1);
  await page.locator('#topology').click();await page.keyboard.press('t');
  check('Surface button and keyboard reach Mobius',(await scene()).topology===2);
  await page.locator('#rule').click();await canvas.click({position:{x:box.width*.4,y:box.height*.55}});
  check('Mirror button creates two sources',(await scene()).sources.length===4);
  const before=(await scene()).sources;await page.locator('#clear').click();check('Clear button empties field',(await scene()).sources.length===0);
  await page.locator('#undo').click();check('Undo restores sources',JSON.stringify((await scene()).sources)===JSON.stringify(before));
  await page.locator('#redo').click();check('Redo clears field',(await scene()).sources.length===0);await page.keyboard.press('z');
  await page.locator('#share').click();const shared=await page.locator('#pattern-link').inputValue();
  check('Share link carries actual model',decodeURIComponent(shared.split('#')[1]).startsWith('FOLDFIELD1|2|1|'));
  await page.locator('#copy-link').click();check('Clipboard action gives a result',(await page.locator('#copy-status').innerText()).length>0);await page.keyboard.press('Escape');
  await page.evaluate(()=>localStorage.removeItem('foldfield.browser.v1'));await page.goto(shared);await ready();
  check('Shared link restores four sources',await page.locator('#count').innerText()==='04');
  await page.locator('#rule').click();await canvas.focus();await page.keyboard.press('ArrowRight');await page.keyboard.press('Shift+Enter');
  check('Keyboard opposed placement creates signed pair',(await scene()).sources.length===6&&(await scene()).sources[4][2]===-1&&(await scene()).sources[5][2]===1);
  check('Edited shared field removes stale hash',!new URL(page.url()).hash);
  await page.reload();await ready();check('Reload restores edited field and undo history',await page.locator('#count').innerText()==='06'&&(await scene()).undo>0);
  const downloadEvent=page.waitForEvent('download');await page.locator('#export').click();const download=await downloadEvent;await download.saveAs(out+'/browser-export.png');
  check('PNG download completes',download.suggestedFilename().endsWith('.png')&&await download.failure()===null);
  await page.locator('#help').click();check('Help opens dialog',await page.locator('#guide').isVisible());await page.keyboard.press('Escape');check('Escape closes help',!await page.locator('#guide').isVisible());
  await page.screenshot({path:out+'/browser-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check('Mobile viewport has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.locator('#negative').click();box=await canvas.boundingBox();await canvas.click({position:{x:box.width*.55,y:box.height*.45}});
  check('Mobile negative control works',(await scene()).sources[6][2]===-1);
  await page.screenshot({path:out+'/browser-mobile.png',fullPage:true});
  await page.route('**/kernels.bin.gz',route=>route.fulfill({status:200,body:'corrupt'}));
  await page.reload();await page.locator('#failure').waitFor({state:'visible'});
  check('Bad wave asset is rejected visibly',await page.locator('#topology').isDisabled()&&(await page.locator('#failure-message').innerText()).includes('invalid format'));
  await page.unroute('**/kernels.bin.gz');await page.locator('#retry').click();await ready();check('Retry recovers after invalid asset',!await page.locator('#failure').isVisible());
  await page.evaluate(()=>localStorage.setItem('foldfield.browser.v1','invalid'));await page.reload();await ready();
  check('Malformed saved state recovers visibly',await page.locator('#count').innerText()==='00'&&(await page.locator('#status').innerText()).includes('invalid'));
  check('No uncaught browser errors',errors.length===0);
  return {passed:checks.length,checks,errors,browser:await page.evaluate(()=>navigator.userAgent)};
}
